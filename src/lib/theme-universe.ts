/** 유니버스 전체가 데이터를 가지는 가장 이른 날 — 백테스트 시작 하한. */
export function commonStart(universe: ThemeEtf[] = THEME_UNIVERSE): string {
  return universe.reduce((max, e) => (e.listedOn > max ? e.listedOn : max), '1900-01-01');
}

