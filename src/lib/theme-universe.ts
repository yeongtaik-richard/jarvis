/**
 * 테마 로테이션 유니버스 — 일반계좌용 ETF 바스켓.
 *
 * ## 왜 ETF인가 (개별종목이 아니라)
 * 초기 자금이 300만원이다. 테마당 100만원이면 **SK하이닉스 1주(약 176만원)도 못 산다.**
 * 고가주가 섞인 테마는 개별종목 구성 자체가 불가능하고, 억지로 맞추면 "살 수 있는 싼
 * 종목만 고른 포트폴리오"가 되어 테마 대표성이 사라진다. 비중 조정은 더 안 된다 —
 * 밴드 이탈분이 20만원인데 1주가 176만원이면 조정 단위가 없다.
 *
 * 덤으로 생존편향도 피한다. 오늘 기준 "테마 대표주 3개"를 골라 과거를 백테스트하면
 * 그건 **3년을 살아남아 대표가 된 종목들**이라, 수익률이 전략의 실력이 아니라 명단을
 * 미래에서 가져온 결과가 된다. ETF는 그때 실제로 존재했고 편입·퇴출을 운용사가 당시
 * 기준으로 처리했다.
 *
 * ## 왜 3개인가
 * 보유 중인 테마는 더 많지만, **백테스트 가능 구간은 가장 어린 ETF가 정한다.**
 *
 * | ETF | 상장일 | 포함 |
 * |---|---|---|
 * | KODEX 반도체 (091160) | 2006-06-27 | ✅ |
 * | KODEX AI반도체핵심장비 (471990) | 2023-11-21 | ✅ |
 * | KODEX AI전력핵심설비 (487240) | 2024-07-09 | ✅ |
 * | KODEX 미국AI광통신네트워크 (0173Y0) | 2026-03-31 | ❌ 제외 |
 * | KODEX 전고체배터리ESS TOP2플러스 (0209D0) | 2026-06-23 | ❌ 제외 |
 *
 * 다섯 개를 다 넣으면 공통 구간이 **2026-06-23부터 약 3개월**이고, 거기에 룩백
 * 3개월을 빼면 백테스트 구간이 **0일**이 된다. 게다가 그 3개월은 전부 AI 상승
 * 구간이라 어떤 규칙을 넣어도 좋아 보인다.
 *
 * 셋으로 줄이면 공통 구간이 **2024-07-09부터 2년 3개월(거래일 약 550일)**이 되고,
 * 2024년 하반기 조정 구간이 들어와 하락 표본이 생긴다.
 *
 * 빠진 둘은 **실제 운용에는 넣되 백테스트 대상에서만 빼는** 선택이 가능하다. 데이터가
 * 쌓이면 그때 합류시킨다.
 */

export interface ThemeEtf {
  /** 테마 식별자 — 비중·성적을 이 키로 기록한다 */
  key: string;
  /** 사람이 읽는 테마 이름 */
  theme: string;
  /** KRX 종목코드 */
  code: string;
  /** ETF 정식 명칭 */
  name: string;
  /** 상장일 (YYYY-MM-DD) — 백테스트 공통 구간을 이 값으로 정한다 */
  listedOn: string;
}

